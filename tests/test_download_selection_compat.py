class TestRecommendedPackages(unittest.TestCase):
    def test_no_model_recommends_two_packages_for_one_target(self):
        from abstractvision.model_capabilities import VisionModelCapabilitiesRegistry

        reg = VisionModelCapabilitiesRegistry()
        for model_id in reg.list_models():
            recommended = {}
            for dl in reg.get(model_id).downloads:
                if dl.recommended:
                    recommended.setdefault(dl.target, []).append(dl.repo_id)
            for target, repos in recommended.items():
                with self.subTest(model=model_id, target=target):
                    self.assertEqual(len(repos), 1, repos)


