            ("apple-silicon", "MiniMaxAI/MiniMax-H3", {"engine": "mlx-gen", "bits": 16}, "MiniMaxAI/MiniMax-H3"),
            ("apple-silicon", "briaai/FIBO", {"target": "mlx", "bits": 4}, "AbstractFramework/fibo-4bit"),
